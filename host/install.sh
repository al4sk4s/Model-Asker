#!/bin/sh
# Registers the Model Asker host for Chrome, Chromium, Brave, Edge and Vivaldi on
# Linux (current user only). Usage:  sh host/install.sh
#
# On Linux the browser finds a native host through a JSON file in
# <config>/<browser>/NativeMessagingHosts/. That file points to a small launcher
# script generated here, with absolute paths to node and claude: browsers started
# from the desktop often don't have your shell's PATH (nvm, ~/.local/bin...).
set -eu

HOST_NAME="com.model_asker.host"
HOST_DIR=$(cd "$(dirname "$0")" && pwd)
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
LAUNCHER="$HOST_DIR/model_asker_host.sh"

NODE=$(command -v node || true)
CLAUDE=$(command -v claude || true)
if [ -z "$NODE" ]; then
  echo "Node.js not found. Install it first (Arch: sudo pacman -S nodejs npm)." >&2
  exit 1
fi
if [ -z "$CLAUDE" ]; then
  echo "Warning: Claude Code ('claude') not found in PATH." >&2
  echo "         Subscription mode won't work until it's installed and logged in." >&2
fi

EXT_ID=$("$NODE" "$HOST_DIR/extension-id.mjs")

# Launcher that the browser runs.
{
  echo "#!/bin/sh"
  echo "# Generated by host/install.sh — the browser starts this script."
  echo "export CLAUDE_BIN=\"$CLAUDE\""
  echo "export PATH=\"$(dirname "$NODE")${CLAUDE:+:$(dirname "$CLAUDE")}:\$PATH\""
  echo "exec \"$NODE\" \"$HOST_DIR/host.js\" \"\$@\""
} > "$LAUNCHER"
chmod +x "$LAUNCHER"

manifest() {
  cat <<EOF
{
  "name": "$HOST_NAME",
  "description": "Model Asker - bridge to Claude Code",
  "path": "$LAUNCHER",
  "type": "stdio",
  "allowed_origins": ["chrome-extension://$EXT_ID/"]
}
EOF
}

# Profile folders of each browser, relative to ~/.config.
BROWSERS="google-chrome google-chrome-beta google-chrome-unstable chromium BraveSoftware/Brave-Browser microsoft-edge microsoft-edge-beta vivaldi"

install_for() {
  mkdir -p "$CONFIG_HOME/$1/NativeMessagingHosts"
  manifest > "$CONFIG_HOME/$1/NativeMessagingHosts/$HOST_NAME.json"
  echo "  + $1"
}

echo "Model Asker host:"
found=0
for browser in $BROWSERS; do
  if [ -d "$CONFIG_HOME/$browser" ]; then
    install_for "$browser"
    found=1
  fi
done
if [ "$found" -eq 0 ]; then
  # No profile yet (browser never opened): install for the most common ones.
  for browser in google-chrome chromium BraveSoftware/Brave-Browser; do
    install_for "$browser"
  done
fi

# Flatpak/Snap browsers run sandboxed and can't start programs outside it.
if [ -d "$HOME/.var/app" ] && ls "$HOME/.var/app" 2>/dev/null | grep -qiE "chrom|brave|edge|vivaldi"; then
  echo "Note: Flatpak browsers can't start native hosts. Use the pacman/AUR version of the browser." >&2
fi

echo "Done."
echo "  Extension ID: $EXT_ID"
echo "  node:   $NODE"
echo "  claude: ${CLAUDE:-(not found)}"
echo "Restart the browser so it picks up the host."
